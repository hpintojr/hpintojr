const kindClass = (k) => (/lab/i.test(k) ? 'k-lab' : /office/i.test(k) ? 'k-office' : 'k-talk');

function lineup(s) {
  if (!s.upcomingWeek?.length) return '';
  const year = s.slug.slice(0, 4);
  const sessionDay = new Date(`${s.slug}T12:00:00-08:00`).getTime();
  const cards = s.upcomingWeek.map((w) => {
    const [m, d] = w.date.split('/');
    const iso = `${year}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`;
    const p = parts(iso);
    const past = new Date(`${iso}T12:00:00-08:00`).getTime() < sessionDay;
    return `
      <article class="lu ${kindClass(w.kind)}${past ? ' past' : ''}">
        <p class="lu-date"><b>${esc(w.date)}</b><span>${p.wd}</span></p>
        <span class="kind">${esc(w.kind)}</span>
        ${past ? '<span class="done">&#10003; Completed</span>' : ''}
        <h3>${esc(w.who)}</h3>
        <p>${esc(w.blurb)}</p>
      </article>`;
  }).join('');
  return `
<section class="band alt" aria-labelledby="w-title">
  <div class="wrap">
    <div class="sec-head">
      <div>
        <p class="eyebrow">Who's up next</p>
        <h2 id="w-title">Labs &amp; guest speaker on deck</h2>
      </div>
      <p>The MCX program lineup leading into ${esc(s.dateLabel)}. Hour one breaks it all down.</p>
    </div>
    <div class="lineup">${cards}
    </div>
  </div>
</section>`;
}

